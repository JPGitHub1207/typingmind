def write_csv(name, fields, rows):
    path = DATA / name
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields, quoting=csv.QUOTE_MINIMAL)
        writer.writeheader()
        for item in rows:
            writer.writerow(item)
    print(f"{name}: {len(rows)}")


